export type MessageKey = keyof typeof en;

const dictionaries: Record<Lang, Record<MessageKey, string>> = { en, tr };

/** Resolve the language preference, following the system when asked to. */
export function resolveLang(preference: string): Lang {
  if (preference === "tr" || preference === "en") return preference;
  const system =
    typeof navigator !== "undefined" ? navigator.language.toLowerCase() : "en";
  return system.startsWith("tr") ? "tr" : "en";
}

export function translator(lang: Lang) {
  const dict = dictionaries[lang];
  return (key: MessageKey): string => dict[key] ?? en[key] ?? key;
}
